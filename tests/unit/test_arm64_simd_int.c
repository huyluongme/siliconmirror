/*
 * Unit tests for the integer Advanced SIMD instructions of the AArch64
 * model (src/cpu/arm64/simd_int.c). Every encoding was produced by the
 * GNU assembler, unless a comment says otherwise; binutils disassembles
 * those built by hand as undefined, or as an instruction that the
 * Cortex-A53 lacks. The expected values come from a model of the
 * instructions written apart from the emulator, after their descriptions
 * in C7.2 of the Arm Architecture Reference Manual, ARM DDI 0487 M.d.
 */

#include <stdint.h>

#include "arm64_test.h"
#include "cpu/arm64/internal.h"
#include "util/macros.h"

#define FPSR_QC (UINT32_C(1) << 27)

/* Check the two halves of Vn. */
#define CHECK_V(c, n, lo, hi)                                                  \
	do {                                                                       \
		CHECK_EQ((c)->v[n].d[0], (uint64_t)(lo));                              \
		CHECK_EQ((c)->v[n].d[1], (uint64_t)(hi));                              \
	} while (0)

/*
 * An instruction with V1 and V2 as sources and V0 as the destination,
 * which some instructions also read; what V0 holds after it, and FPSR.QC.
 */
typedef struct Case {
	uint32_t insn;
	uint64_t n_lo, n_hi, m_lo, m_hi, d_lo, d_hi;
	uint64_t want_lo, want_hi;
	unsigned qc;
} Case;

static void run_cases(const Case *cases, unsigned count)
{
	for (unsigned i = 0; i < count; i++) {
		const Case *k = &cases[i];
		Arm64Cpu *c;
		Machine *m = arm64_test_machine(&c);

		set_v(c, 1, k->n_lo, k->n_hi);
		set_v(c, 2, k->m_lo, k->m_hi);
		set_v(c, 0, k->d_lo, k->d_hi);
		c->fpsr = 0x80; /* IDC: other bits stay */
		CHECK_EQ(arm64_test_step(m, c, k->insn), MACHINE_STOP_LIMIT);
		if (c->v[0].d[0] != k->want_lo || c->v[0].d[1] != k->want_hi ||
		    c->fpsr != (0x80 | (k->qc ? FPSR_QC : 0)) ||
		    c->pc != RESET_PC + 4) {
			fprintf(stderr,
			        "0x%08" PRIx32 ": V0 = 0x%016" PRIx64 "_%016" PRIx64
			        ", FPSR 0x%" PRIx32 "\n",
			        k->insn, c->v[0].d[1], c->v[0].d[0], c->fpsr);
			test_failures++;
		}
		machine_destroy(m);
	}
}

