static void test_floating_point_encodings(void)
{
	Arm64Cpu *c;
	Machine *m = arm64_test_machine(&c);

	for (unsigned i = 0; i < ARRAY_SIZE(fp_sweep); i++) {
		Arm64Exec want =
			fp_sweep[i].fp ? ARM64_EXEC_UNIMPLEMENTED : ARM64_EXEC_UNDEFINED;
		Arm64Exec got = arm64_execute(c, fp_sweep[i].insn);

		if (got != want) {
			fprintf(stderr, "0x%08" PRIx32 ": %d, not %d\n", fp_sweep[i].insn,
			        (int)got, (int)want);
			test_failures++;
		}
	}
	machine_destroy(m);
}

