static void test_register_numbers(void)
{
	for (unsigned i = 0; i < ARRAY_SIZE(register_pairs); i++) {
		Arm64Cpu *c;
		Machine *m = arm64_test_machine(&c);
		Arm64Vreg lo_result;

		for (unsigned r = 0; r < 32; r++)
			set_v(c, r, 0x0123456789abcdef * (r + 3),
			      0xfedcba9876543210 ^ r * 77);
		arm64_test_exec(m, c, register_pairs[i].lo);
		lo_result = c->v[0];
		uint32_t lo_fpsr = c->fpsr;

		c->fpsr = 0;
		for (unsigned r = 0; r < 4; r++)
			c->v[register_pairs[i].map[r]] = c->v[r];
		for (unsigned r = 0; r < 4; r++)
			set_v(c, r, 0x0123456789abcdef * (r + 3),
			      0xfedcba9876543210 ^ r * 77);
		/* Vd starts as Vd of the first run did, for the accumulating ones. */
		set_v(c, register_pairs[i].map[0], 0x0123456789abcdef * 3,
		      0xfedcba9876543210);
		arm64_test_exec(m, c, register_pairs[i].hi);
		if (c->v[register_pairs[i].map[0]].d[0] != lo_result.d[0] ||
		    c->v[register_pairs[i].map[0]].d[1] != lo_result.d[1] ||
		    c->fpsr != lo_fpsr || c->v[0].d[0] != 0x0123456789abcdef * 3) {
			fprintf(stderr, "0x%08" PRIx32 " differs from 0x%08" PRIx32 "\n",
			        register_pairs[i].hi, register_pairs[i].lo);
			test_failures++;
		}
		machine_destroy(m);
	}
}

/* QC stays set, and registers other than V0 and V1 work. */
static void test_qc_and_registers(void)
{
	Arm64Cpu *c;
	Machine *m = arm64_test_machine(&c);

	c->fpsr = FPSR_QC;
	set_v(c, 1, 1, 2);
	arm64_test_exec(m, c, 0x4e207820); /* SQABS V0.16B, V1.16B */
	CHECK_EQ(c->fpsr, FPSR_QC);
	CHECK_V(c, 0, 1, 2);
	set_v(c, 22, 0x0102030405060708, 0x1112131415161718);
	set_v(c, 17, UINT64_MAX, UINT64_MAX);
	arm64_test_exec(m, c, 0x4e205ad1); /* CNT V17.16B, V22.16B */
	CHECK_V(c, 17, 0x0101020102020301, 0x0202030203030402);
	arm64_test_exec(m, c, 0x4e31bad1); /* ADDV B17, V22.16B */
	CHECK_V(c, 17, 0xc8, 0);
	arm64_test_exec(m, c, 0x5ef1bad1); /* ADDP D17, V22.2D */
	CHECK_V(c, 17, 0x121416181a1c1e20, 0);
	machine_destroy(m);
}

/* The traps of SIMD&FP apply: CPACR_EL1.FPEN = 00 at EL1. */
static void test_trapped(void)
{
	static const uint32_t insns[] = {
		0x4e205820, /* CNT V0.16B, V1.16B */
		0x5ee0b820, /* ABS D0, D1 */
		0x4e31b820, /* ADDV B0, V1.16B */
		0x5ef1b820, /* ADDP D0, V1.2D */
		0x6e228c20, /* CMEQ V0.16B, V1.16B, V2.16B */
		0x5e220c20, /* SQADD B0, B1, B2 */
		0x4f1d8420, /* SHRN2 V0.8H, V1.4S, #3 */
		0x5f7d0420, /* SSHR D0, D1, #3 */
		0x4e032020, /* TBL V0.16B, {V1.16B, V2.16B}, V3.16B */
		0x4e427820, /* ZIP2 V0.8H, V1.8H, V2.8H */
		0x6e022820, /* EXT V0.16B, V1.16B, V2.16B, #5 */
		0x4e62c020, /* SMULL2 V0.4S, V1.8H, V2.8H */
		0x5e62d020, /* SQDMULL S0, H1, H2 */
		0x6f720820, /* MLA V0.8H, V1.8H, V2.H[7] */
		0x5f52c820, /* SQDMULH H0, H1, V2.H[5] */
	};

	for (unsigned i = 0; i < ARRAY_SIZE(insns); i++) {
		Arm64Cpu *c;
		Machine *m = arm64_test_machine(&c);

		c->sys.scr_el3 = ARM64_SCR_RW | ARM64_SCR_NS;
		c->sys.hcr_el2 = ARM64_HCR_RW;
		c->el = 1;
		set_v(c, 0, 5, 6);
		CHECK_EQ(arm64_test_step(m, c, insns[i]), MACHINE_STOP_LIMIT);
		CHECK_EQ(c->el, 1);
		CHECK_EQ(c->sys.esr[1], 0x1fe00000);
		CHECK_V(c, 0, 5, 6);
		machine_destroy(m);
	}
}

